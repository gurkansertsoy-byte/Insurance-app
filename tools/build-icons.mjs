// Extracts the Lucide icons used by the app into js/icons.js.
// Usage: node tools/build-icons.mjs <path-to-lucide-static/icons>
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-icons.mjs <lucide-static/icons>'); process.exit(1); }

const names = `layout-dashboard users user user-plus file-text calendar-days calendar refresh-cw wallet list-checks
chart-column upload settings plus search sun moon monitor download trash-2 pencil phone message-circle mail printer x
chevron-left chevron-right chevron-down chevron-up triangle-alert check info car house heart-pulse shield shield-check
funnel arrow-up-down ellipsis copy git-merge undo-2 file-spreadsheet database languages clock calendar-clock banknote
credit-card lightbulb list history external-link menu eye eye-off cloud-upload folder-open save rotate-ccw circle-check
circle-alert circle-x hand-coins receipt notebook-pen sticky-note link arrow-right arrow-left briefcase building-2 plane
hard-drive keyboard command zap star filter-x sparkles badge-percent calculator file-down file-up chart-pie trending-up
trending-down ban file-x unlink link-2 file-check file-warning lock cloud-check cloud-alert refresh-ccw file-search`.split(/\s+/).filter(Boolean);

const out = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
  out[n] = inner;
}
const js = `/* Icons from Lucide (https://lucide.dev) - ISC License, Copyright (c) Lucide Icons and Contributors.
   Generated by tools/build-icons.mjs - do not edit by hand. */
(function (root) {
  root.ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(new URL('../js/icons.js', import.meta.url), js);
console.log('wrote', Object.keys(out).length, 'icons');
