// Embeds sample-data/ornek-portfoy.xlsx into js/sample-data.js so the demo also works from file://.
import fs from 'node:fs';

const xlsx = fs.readFileSync(new URL('../sample-data/ornek-portfoy.xlsx', import.meta.url));
const js = `/* Sample workbook (fictional data) - generated by tools/build-sample-js.mjs */
window.SAMPLE_XLSX_BASE64 = ${JSON.stringify(xlsx.toString('base64'))};
`;
fs.writeFileSync(new URL('../js/sample-data.js', import.meta.url), js);
console.log('wrote js/sample-data.js', Math.round(js.length / 1024), 'KB');
